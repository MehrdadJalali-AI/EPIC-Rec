"""Write manuscript/numbers.tex and the result tables from the certified report.

Reads the CSV tables and accuracy files of the reproducible study. Does not recompute
experiments. Percentages and intervals are the stored report values, rounded for display.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1] / "results"
OUT = Path(__file__).resolve().parents[1] / "manuscript"
TABLES = ROOT / "report" / "tables"

SHORT = {"movielens-1m": "ML", "lastfm": "LF"}
SETTING = {"A": "C1", "A3": "C1 + C3", "B": "C1 + C2", "C": "C1 + C2 + C3"}
STAG = {"A": "A", "A3": "AThree", "B": "B", "C": "C"}
RANK_NAME = {1: "One", 10: "Ten"}
QUARTILE_NAME = {0: "Short", 1: "Second", 2: "Third", 3: "Long"}
ALPHA_NAME = {0.25: "Low", 0.5: "Half", 0.75: "High", 1.0: "One"}
K_NAME = {5: "Five", 10: "Ten", 20: "Twenty"}


def pct(x: float, nd: int = 2) -> str:
    return f"{float(x):.{nd}f}"


def num(x: float, nd: int = 2) -> str:
    return f"{float(x):.{nd}f}"


def tex_int(n: int) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def main() -> None:
    feas = pd.read_csv(TABLES / "feasibility_by_setting.csv")
    paired = pd.read_csv(TABLES / "paired_mask_size_differences.csv")
    rank = pd.read_csv(TABLES / "feasibility_by_rank.csv")
    quartile = pd.read_csv(TABLES / "feasibility_by_history_quartile.csv")
    approx = pd.read_csv(TABLES / "exact_vs_approximate.csv")
    evidence = pd.read_csv(TABLES / "evidence_survival.csv")
    causes = pd.read_csv(TABLES / "infeasibility_causes.csv")
    semantics = pd.read_csv(TABLES / "p_vs_p_eps.csv")
    cert = pd.read_csv(TABLES / "certification.csv")
    sizes = pd.read_csv(TABLES / "mask_size_distribution.csv")

    macros: list[str] = [
        "% generated by scripts/manuscript_from_report.py from the certified report -- do not edit",
        r"\newcommand{\NUsers}{200}",
        r"\newcommand{\NPairs}{2{,}000}",
        r"\newcommand{\UsersPerQ}{50}",
        r"\newcommand{\TimeLimit}{20}",
        r"\newcommand{\CertLimit}{60}",
        r"\newcommand{\EnumMax}{14}",
        r"\newcommand{\ThreatInit}{40}",
        r"\newcommand{\BeamWidth}{5}",
        r"\newcommand{\BeamDepth}{15}",
        r"\newcommand{\HeurDepth}{15}",
        r"\newcommand{\NBoot}{2{,}000}",
        r"\newcommand{\Eps}{10^{-6}}",
    ]
    for ds, acc_name in (("movielens-1m", "movielens-1m"), ("lastfm", "lastfm")):
        acc = json.loads((ROOT / acc_name / "accuracy.json").read_text())
        tag = SHORT[ds]
        st = acc["stats"]
        macros.append(f"\\newcommand{{\\{tag}DataUsers}}{{{tex_int(st['users'])}}}")
        macros.append(f"\\newcommand{{\\{tag}DataItems}}{{{tex_int(st['items'])}}}")
        macros.append(f"\\newcommand{{\\{tag}KGRel}}{{{len(st['kg_relations'])}}}")
        macros.append(f"\\newcommand{{\\{tag}ItemsKG}}{{{tex_int(st['items_with_kg'])}}}")
        models = acc["models"]
        macros.append(f"\\newcommand{{\\{tag}ThetaCo}}{{{models['path_additive']['theta']['co']:.2f}}}")
        macros.append(f"\\newcommand{{\\{tag}Beta}}{{{models['path_additive']['beta']:.2f}}}")
        for key, cmd in (
            ("popularity", "Pop"),
            ("itemknn", "ItemKNN"),
            ("bprmf", "BPR"),
            ("path_additive_kg_only", "KG"),
            ("path_additive", "Full"),
        ):
            te = models[key]["test"]
            macros.append(f"\\newcommand{{\\{tag}Rec{cmd}}}{{{100 * te['recall@20']:.1f}}}")
            macros.append(f"\\newcommand{{\\{tag}Ndcg{cmd}}}{{{100 * te['ndcg@20']:.1f}}}")
        cover, evfree, n = _coverage(ROOT / acc_name / "main" / "records.jsonl")
        macros.append(f"\\newcommand{{\\{tag}Scope}}{{{100 * cover:.1f}}}")
        macros.append(f"\\newcommand{{\\{tag}EvFree}}{{{evfree}}}")
        macros.append(f"\\newcommand{{\\{tag}ScopeN}}{{{n}}}")

    main_f = feas[(feas.experiment == "main") & (feas.K == 10) & (feas.alpha == 0.5)]
    for _, r in main_f.iterrows():
        tag = SHORT[r.dataset] + STAG[r.setting]
        for col, name in (
            ("optimal", "Opt"),
            ("feasible", "Feas"),
            ("infeasible", "Inf"),
            ("timeout", "Tout"),
            ("mask_exists", "Exists"),
            ("mask_exists_lo", "ExistsLo"),
            ("mask_exists_hi", "ExistsHi"),
            ("runtime_median_s", "Time"),
            ("runtime_max_s", "TimeMax"),
        ):
            nd = 2 if name.startswith("Time") else 2
            macros.append(f"\\newcommand{{\\{tag}{name}}}{{{pct(r[col], nd)}}}")
        macros.append(f"\\newcommand{{\\{tag}Killed}}{{{int(r.killed)}}}")

    comp_name = {"B - A": "BA", "C - B": "CB", "A3 - A": "AThreeA", "C - A3": "CAThree"}
    for _, r in paired[paired.experiment == "main"].iterrows():
        if r.comparison not in comp_name:
            continue
        comp = comp_name[r.comparison]
        tag = SHORT[r.dataset] + comp
        macros.append(f"\\newcommand{{\\{tag}N}}{{{int(r.pairs)}}}")
        macros.append(f"\\newcommand{{\\{tag}Users}}{{{int(r.users)}}}")
        macros.append(f"\\newcommand{{\\{tag}Mean}}{{{num(r['mean'], 3)}}}")
        macros.append(f"\\newcommand{{\\{tag}Lo}}{{{num(r.mean_lo, 3)}}}")
        macros.append(f"\\newcommand{{\\{tag}Hi}}{{{num(r.mean_hi, 3)}}}")
        macros.append(f"\\newcommand{{\\{tag}Med}}{{{num(r['median'], 0)}}}")
        macros.append(f"\\newcommand{{\\{tag}Pos}}{{{num(r.share_positive, 1)}}}")
        macros.append(f"\\newcommand{{\\{tag}Neg}}{{{int(r.share_negative)}}}")

    rank_m = rank[(rank.experiment == "main") & (rank.K == 10)]
    for _, r in rank_m[rank_m["rank"].isin([1, 10])].iterrows():
        tag = f"{SHORT[r.dataset]}{STAG[r.setting]}R{RANK_NAME[int(r['rank'])]}"
        macros.append(f"\\newcommand{{\\{tag}}}{{{pct(r.mask_exists, 1)}}}")
    q_m = quartile[(quartile.experiment == "main") & (quartile.K == 10)]
    for _, r in q_m.iterrows():
        tag = f"{SHORT[r.dataset]}{STAG[r.setting]}Q{QUARTILE_NAME[int(r.stratum)]}"
        macros.append(f"\\newcommand{{\\{tag}}}{{{pct(r.mask_exists, 1)}}}")

    ev = evidence[(evidence.experiment == "main") & (evidence.method == "exact") & (evidence.setting.isin(["B", "C"]))]
    for _, r in ev.iterrows():
        macros.append(f"\\newcommand{{\\{SHORT[r.dataset]}Kendall{r.setting}}}{{{num(r.kendall_mean)}}}")

    ap = approx[(approx.experiment == "main") & (approx.setting == "C")]
    for _, r in ap.iterrows():
        key = r.method.replace("c1_stop", "cOneStop").replace(":", "").replace("_", "")
        tag = SHORT[r.dataset] + "C" + key
        macros.append(f"\\newcommand{{\\{tag}Succ}}{{{pct(r.success)}}}")
        macros.append(f"\\newcommand{{\\{tag}OnOpt}}{{{pct(r.success_on_optimal)}}}")
        macros.append(f"\\newcommand{{\\{tag}Exact}}{{{pct(r.exact_size_share)}}}")
        if r.method == "greedy:target_score:c1_stop":
            cond_list = 100 * r.c1_c2 / r.c1
            cond_all = 100 * r.c1_c2_c3 / r.c1
            macros.append(f"\\newcommand{{\\{SHORT[r.dataset]}CStopCOne}}{{{pct(r.c1)}}}")
            macros.append(f"\\newcommand{{\\{SHORT[r.dataset]}CStopList}}{{{pct(cond_list, 1)}}}")
            macros.append(f"\\newcommand{{\\{SHORT[r.dataset]}CStopAll}}{{{pct(cond_all, 1)}}}")

    thr = feas[feas.experiment == "threshold"].sort_values("alpha")
    for _, r in thr.iterrows():
        macros.append(
            f"\\newcommand{{\\AlphaExists{ALPHA_NAME[round(float(r.alpha), 2)]}}}{{{pct(r.mask_exists, 1)}}}")
    ks = feas[feas.experiment == "k_sweep"]
    for _, r in ks.iterrows():
        kn = K_NAME[int(r.K)]
        macros.append(f"\\newcommand{{\\K{kn}{STAG[r.setting]}Exists}}{{{pct(r.mask_exists, 2)}}}")
        macros.append(f"\\newcommand{{\\K{kn}{STAG[r.setting]}Tout}}{{{pct(r.timeout, 2)}}}")

    sem = semantics[semantics.experiment == "margin"]
    if not ((sem.status_differs == 0) & (sem.optimum_differs == 0) & (sem.milp_agrees == sem.milp_decided)).all():
        raise SystemExit("P versus P_eps table is not uniformly in agreement; refusing to summarise it")
    macros.append(f"\\newcommand{{\\EnumPairs}}{{{int(sem.pairs.iloc[0])}}}")
    macros.append(f"\\newcommand{{\\EnumUsers}}{{{int(sem.users.iloc[0])}}}")
    macros.append(f"\\newcommand{{\\EnumAgree}}{{{int(sem.milp_agrees.iloc[0])}}}")

    for ds, tag in SHORT.items():
        sub = cert[(cert.dataset == ds) & (cert.experiment == "main")]
        counts = sub.groupby("certification").pairs.sum()
        labels = {"confirmed": "Confirmed", "corrected": "Corrected", "undecided": "Undecided",
                  "not_applicable": "NotApplicable"}
        for name, label in labels.items():
            macros.append(f"\\newcommand{{\\{tag}Cert{label}}}{{{int(counts.get(name, 0))}}}")

    cause_m = causes[(causes.experiment == "main") & (causes.setting == "C")]
    for _, r in cause_m.iterrows():
        if str(r.infeasibility_cause).startswith("list entanglement"):
            macros.append(f"\\newcommand{{\\{SHORT[r.dataset]}CauseList}}{{{pct(r.share, 1)}}}")
        elif str(r.infeasibility_cause).startswith("evidence entanglement"):
            macros.append(f"\\newcommand{{\\{SHORT[r.dataset]}CauseEv}}{{{pct(r.share, 1)}}}")
        elif str(r.infeasibility_cause).startswith("joint conflict"):
            macros.append(f"\\newcommand{{\\{SHORT[r.dataset]}CauseJoint}}{{{pct(r.share, 1)}}}")

    macros.append(f"\\newcommand{{\\SmallerThanOpt}}{{{int(approx.smaller_than_optimum.sum())}}}")
    macros.append(f"\\newcommand{{\\SuccessOnInf}}{{{int(approx.success_on_infeasible.sum())}}}")
    (OUT / "numbers.tex").write_text("\n".join(macros) + "\n")
    (OUT / "tab_status.tex").write_text(_status_table(main_f))
    (OUT / "tab_paired.tex").write_text(_paired_table(paired[paired.experiment == "main"]))
    (OUT / "tab_rank.tex").write_text(_rank_table(rank_m))
    (OUT / "tab_quartile.tex").write_text(_quartile_table(q_m))
    (OUT / "tab_heuristics.tex").write_text(_heur_table(approx[approx.experiment == "main"]))
    (OUT / "tab_alpha.tex").write_text(_alpha_table(thr, sizes))
    (OUT / "tab_K.tex").write_text(_k_table(ks))
    (OUT / "tab_semantics.tex").write_text(_sem_table(sem))
    _figure(main_f, rank_m)
    print(f"wrote {len(macros)} macros and 8 tables")


def _coverage(path: Path) -> tuple[float, int, int]:
    cover = n = ev = 0
    for line in path.open():
        r = json.loads(line)
        if r.get("method") != "exact" or r.get("setting") != "A":
            continue
        n += 1
        cover += r["domain_size"] / r["hist_len"]
        ev += int(bool(r.get("evidence_free")))
    if n != 2000:
        raise SystemExit(f"{path}: expected 2000 setting-A pairs, found {n}")
    return cover / n, ev, n


def _status_table(df: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"Dataset & Setting & Optimal & Feasible & Infeasible & Timeout & Exists [95\% CI] \\",
        r"\midrule",
    ]
    order = {"movielens-1m": 0, "lastfm": 1}
    show = df.copy()
    show["_o"] = show.dataset.map(order)
    show["_s"] = show.setting.map({"A": 0, "A3": 1, "B": 2, "C": 3})
    for _, r in show.sort_values(["_o", "_s"]).iterrows():
        name = "MovieLens-1M" if r.dataset == "movielens-1m" else "Last.fm"
        ci = f"{pct(r.mask_exists)} [{pct(r.mask_exists_lo)}, {pct(r.mask_exists_hi)}]"
        lines.append(
            f"{name} & {SETTING[r.setting]} & {pct(r.optimal)} & {pct(r.feasible)} & "
            f"{pct(r.infeasible)} & {pct(r.timeout)} & {ci} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _paired_table(df: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"Dataset & Comparison & Pairs (users) & Mean [95\% CI] & Median & Share $>0$ \\",
        r"\midrule",
    ]
    label = {"B - A": r"C1+C2 $-$ C1", "C - B": r"C1+C2+C3 $-$ C1+C2", "A3 - A": r"C1+C3 $-$ C1"}
    keep = df[df.comparison.isin(label)]
    keep = keep.copy()
    keep["_o"] = keep.dataset.map({"movielens-1m": 0, "lastfm": 1})
    keep["_c"] = keep.comparison.map({"B - A": 0, "C - B": 1, "A3 - A": 2})
    for _, r in keep.sort_values(["_o", "_c"]).iterrows():
        name = "MovieLens-1M" if r.dataset == "movielens-1m" else "Last.fm"
        lines.append(
            f"{name} & {label[r.comparison]} & {int(r.pairs)} ({int(r.users)}) & "
            f"{num(r['mean'], 3)} [{num(r.mean_lo, 3)}, {num(r.mean_hi, 3)}] & {num(r['median'], 0)} & "
            f"{num(r.share_positive, 1)}\\% \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _rank_table(df: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{rcccc}",
        r"\toprule",
        r"Rank & ML C1+C2 & ML C1+C2+C3 & LF C1+C2 & LF C1+C2+C3 \\",
        r"\midrule",
    ]
    for rk in range(1, 11):
        cells = []
        for ds, st in (("movielens-1m", "B"), ("movielens-1m", "C"), ("lastfm", "B"), ("lastfm", "C")):
            hit = df[(df.dataset == ds) & (df.setting == st) & (df["rank"] == rk)]
            cells.append(pct(hit.mask_exists.iloc[0], 1))
        lines.append(f"{rk} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _quartile_table(df: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"History quartile & ML C1+C2 & ML C1+C2+C3 & LF C1+C2 & LF C1+C2+C3 \\",
        r"\midrule",
    ]
    names = {0: "shortest", 1: "second", 2: "third", 3: "longest"}
    for q in range(4):
        cells = []
        for ds, st in (("movielens-1m", "B"), ("movielens-1m", "C"), ("lastfm", "B"), ("lastfm", "C")):
            hit = df[(df.dataset == ds) & (df.setting == st) & (df.stratum == q)]
            cells.append(pct(hit.mask_exists.iloc[0], 1))
        lines.append(f"{names[q]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _heur_table(df: pd.DataFrame) -> str:
    order = [
        "beam",
        "greedy:violation",
        "continuous:sigmoid:attribution:repair",
        "continuous:gumbel:attribution:repair",
        "greedy:margin",
        "greedy:list_aware",
        "greedy:target_score",
        "greedy:target_score:c1_stop",
        "greedy:popularity",
        "greedy:random",
    ]
    nice = {
        "beam": "beam search",
        "greedy:violation": "violation greedy",
        "continuous:sigmoid:attribution:repair": "continuous, sigmoid",
        "continuous:gumbel:attribution:repair": "continuous, Gumbel",
        "greedy:margin": "ranking-margin order",
        "greedy:list_aware": "list-aware order",
        "greedy:target_score": "target-score order",
        "greedy:target_score:c1_stop": "target-score, stop at C1",
        "greedy:popularity": "popularity order",
        "greedy:random": "random order",
    }
    lines = [
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r" & \multicolumn{2}{c}{MovieLens-1M} & \multicolumn{2}{c}{Last.fm} \\",
        r"Method & success & exact size & success & exact size \\",
        r"\midrule",
    ]
    sub = df[df.setting == "C"]
    for method in order:
        cells = []
        for ds in ("movielens-1m", "lastfm"):
            r = sub[(sub.dataset == ds) & (sub.method == method)].iloc[0]
            cells += [pct(r.success), pct(r.exact_size_share)]
        lines.append(nice[method] + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _alpha_table(feas: pd.DataFrame, sizes: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{ccccc}",
        r"\toprule",
        r"$\alpha$ & Exists & Optimal & Infeasible & Mean $|M|$ on optima \\",
        r"\midrule",
    ]
    sz = sizes[(sizes.experiment == "threshold") & (sizes.setting == "C")]
    for _, r in feas.sort_values("alpha").iterrows():
        part = sz[sz.alpha == r.alpha]
        mean = (part["size"] * part.pairs).sum() / part.pairs.sum()
        lines.append(
            f"{r.alpha:.2f} & {pct(r.mask_exists, 1)} & {pct(r.optimal, 1)} & "
            f"{pct(r.infeasible, 1)} & {num(mean)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _k_table(df: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{ccccccc}",
        r"\toprule",
        r" & \multicolumn{2}{c}{C1} & \multicolumn{2}{c}{C1 + C2} & \multicolumn{2}{c}{C1 + C2 + C3} \\",
        r"$K$ & exists & timeout & exists & timeout & exists & timeout \\",
        r"\midrule",
    ]
    for k in (5, 10, 20):
        cells = [str(k)]
        for st in ("A", "B", "C"):
            r = df[(df.K == k) & (df.setting == st)].iloc[0]
            cells += [pct(r.mask_exists, 2), pct(r.timeout, 2)]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _sem_table(df: pd.DataFrame) -> str:
    lines = [
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"$\varepsilon$ & Pairs (users) & Status or optimum differs & MILP agrees \\",
        r"\midrule",
    ]
    for eps, g in df.groupby("eps"):
        if g.pairs.nunique() != 1 or g.users.nunique() != 1:
            raise SystemExit("semantics rows disagree within an epsilon")
        lines.append(
            f"$10^{{{int(round(__import__('math').log10(eps)))}}}$ & "
            f"{int(g.pairs.iloc[0])} ({int(g.users.iloc[0])}) & "
            f"{int(g.status_differs.sum() + g.optimum_differs.sum())} & "
            f"{int(g.milp_agrees.sum())}/{int(g.milp_decided.sum())} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def _figure(feas: pd.DataFrame, rank: pd.DataFrame) -> None:
    plt.rcParams.update({
        "font.family": "DejaVu Sans",
        "font.size": 8,
        "axes.linewidth": 0.6,
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
    })
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.8))
    settings = ["A", "A3", "B", "C"]
    labels = ["C1", "C1+C3", "C1+C2", "C1+C2+C3"]
    colors = {"movielens-1m": "#3b6ea5", "lastfm": "#d1495b"}
    names = {"movielens-1m": "MovieLens-1M", "lastfm": "Last.fm"}
    ax = axes[0]
    import numpy as np
    x = np.arange(len(settings))
    for i, ds in enumerate(("movielens-1m", "lastfm")):
        rows = [feas[(feas.dataset == ds) & (feas.setting == s)].iloc[0] for s in settings]
        y = [r.mask_exists for r in rows]
        lo = [r.mask_exists - r.mask_exists_lo for r in rows]
        hi = [r.mask_exists_hi - r.mask_exists for r in rows]
        ax.bar(x + (i - 0.5) * 0.36, y, 0.36, yerr=[lo, hi], color=colors[ds], label=names[ds],
               error_kw=dict(lw=0.6, capsize=2, capthick=0.6))
        for xi, yi in zip(x + (i - 0.5) * 0.36, y):
            if abs(yi - round(yi, 2)) > 1e-6:
                raise SystemExit(f"figure value {yi} is not the stored percentage")
    ax.set_xticks(x, labels)
    ax.set_ylim(0, 112)
    ax.set_ylabel("Mask exists (%)")
    ax.set_title("By constraint")
    ax.legend(frameon=False, loc="lower left")
    ax = axes[1]
    for ds, style in (("movielens-1m", "-"), ("lastfm", "--")):
        for st, color in (("B", "#3b6ea5"), ("C", "#c9962a")):
            sub = rank[(rank.dataset == ds) & (rank.setting == st)].sort_values("rank")
            ax.plot(sub["rank"], sub.mask_exists, style, color=color, lw=1.2,
                    label=f"{names[ds].split('-')[0]} {SETTING[st]}")
    ax.set_xticks(range(1, 11))
    ax.set_ylim(0, 105)
    ax.set_xlabel("Initial rank of the target")
    ax.set_ylabel("Mask exists (%)")
    ax.set_title("By rank")
    ax.legend(frameon=False, fontsize=6, ncol=2)
    fig.tight_layout()
    dest = OUT / "figures"
    dest.mkdir(exist_ok=True)
    fig.savefig(dest / "feasibility.pdf")
    plt.close(fig)


if __name__ == "__main__":
    main()
